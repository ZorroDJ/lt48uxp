#ifndef LT48_PIC_PHYSICAL_QFN44_H
#define LT48_PIC_PHYSICAL_QFN44_H
#include "profile.h"
/* Authored direct QFN44 programming join shared by DS41332D and DS30492B.
 * Callers first enforce exact source/silicon binding. */
static inline lt48_status lt48_pic_qfn44_programming_map(lt48_pin_map **pins){
 if(!pins||!*pins||lt48_pin_map_package_pin_count(*pins)!=44)return LT48_SAFETY_REJECTED;
 static const unsigned char bytes[]={0x3,0x4,0x0,0x2,0x0,0x3,0x0,0x6,0x7,0x1b,0x1,0x0,0x3,0x0,0x5,0x1d,0x1e,0x3,0x0,0x23,0x0,0x0,0x1,0x2,0x3,0x4,0x8,0x9,0xa,0xb,0xc,0xd,0xe,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1c,0x1f,0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27,0x28,0x29,0x2a,0x2b,0x0,0x0,0x6,0x0,0x17,0x0,0xf,0x0,0x18,0x0,0x10,0x0,0xe,0x0,0x11,0x0};
 const lt48_pin_code code={44,bytes,sizeof(bytes)};lt48_pin_map *selected=NULL;
 lt48_status st=lt48_pin_map_parse(&code,&selected);
 if(st==LT48_OK){lt48_pin_map_close(*pins);*pins=selected;}
 return st;
}
#endif
