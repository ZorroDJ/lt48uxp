static inline lt48_status lt48_pic18_patch_panel_setup(const unsigned char *original,size_t size,
 uint16_t address,unsigned char *output,size_t capacity){
 static const struct{unsigned char hash[32];size_t size,offset;unsigned char value;} allowed[]={
 {{0xc7,0x84,0xa2,0x06,0xb7,0xdb,0xa7,0xeb,0x10,0x5d,0x31,0x42,0x74,0x22,0x74,0xd1,0x6b,0x2f,0x55,0xfc,0xd0,0xc2,0x97,0x71,0x58,0x32,0xce,0x77,0x2b,0x72,0xf0,0xf1},2118,0x262,0x40},
 {{0x21,0xf5,0x20,0xb7,0x46,0xea,0xfa,0x2a,0xb8,0xdd,0xb5,0x5a,0x50,0x85,0x75,0x8b,0xa8,0x8d,0x76,0xf2,0x75,0x18,0x0b,0x30,0x50,0x5e,0x1c,0xed,0x57,0xcc,0xf6,0xb7},2118,0x262,0x40},
 {{0x3a,0x90,0x1d,0x2e,0x50,0x87,0xd2,0x87,0x40,0x30,0x4a,0xd5,0x4e,0xc4,0xda,0x46,0x44,0x25,0xb9,0xfa,0xd0,0x59,0x56,0xa6,0xf9,0x80,0xc5,0xef,0x16,0x72,0xf2,0x3f},2004,0x259,0x0c},
 };
 if(!original||!output||original==output)return LT48_INVALID_ARGUMENT;
 if(capacity<size)return LT48_BUFFER_TOO_SMALL;
 if(address!=0x8000)return LT48_SAFETY_REJECTED;
 unsigned char hash[32];lt48_sha256(original,size,hash);
 for(size_t i=0;i<sizeof allowed/sizeof *allowed;i++){
  if(size!=allowed[i].size||memcmp(hash,allowed[i].hash,32))continue;
  if(original[allowed[i].offset]!=allowed[i].value||original[allowed[i].offset-1]!=0x74)return LT48_SAFETY_REJECTED;
  if(size==2004&&memcmp(original+0x43f,"\x7f\x0a\xdf\xfe",4))return LT48_SAFETY_REJECTED;
  memcpy(output,original,size);output[allowed[i].offset]=0;
  if(size==2004)output[0x440]=200;
  return LT48_OK;
 }
 return LT48_SAFETY_REJECTED;
}
