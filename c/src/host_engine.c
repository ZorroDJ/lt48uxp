lt48_status lt48_host_engine_for_class(
    uint16_t device_class,
    lt48_host_engine_info *out_info
) {
    if (out_info == NULL) return LT48_INVALID_ARGUMENT;
    if (device_class < 2000u || device_class > 2048u)
        return LT48_NOT_FOUND;
    *out_info = engines[device_class - 2000u];
    return LT48_OK;
}
